#!/usr/bin/env node
// ── Report export regression suite (v5.6) ──
// Covers:
//   1. IconDownloadReport — improved SVG export glyph in Icons.jsx
//   2. fileExportClient — buildReportFilename, MD/TXT/HTML report builders
//      (slug math, citation linkify, XSS escaping, blob types)
//   3. fileExportHeavy — exportReportAsPDF / exportReportAsDOCX exports
//   4. ExportMenu component — badge chips, click-outside/Escape, a11y
//   5. Page wiring — research (MD/PDF/DOCX/HTML), reelpen (MD/TXT/PDF),
//      study (MD/TXT/PDF), devtools (MD/TXT/PDF) + reelpen box height fix
//   6. i18n — export.* keys present
import assert from 'node:assert'
import { readFileSync } from 'node:fs'

let pass = 0, fail = 0
function t(name, fn) {
  try {
    if (typeof fn === 'function') fn()
    else if (fn) { pass++; return }
    else throw new Error('falsy')
    pass++
  } catch (err) {
    fail++
    console.error(`  ✗ ${name}${err?.message ? ` — ${err.message}` : ''}`)
  }
}

const read = (p) => readFileSync(new URL(p, import.meta.url), 'utf8')

// ── 1. IconDownloadReport ────────────────────────────────────────────────
console.log('── 1. IconDownloadReport glyph ──')
const iconsSrc = read('../components/Icons.jsx')
t('IconDownloadReport is exported', iconsSrc.includes('export function IconDownloadReport'))
t('report sheet body path (dog-eared doc like IconFile)', iconsSrc.includes('M4 2h5l4 4v7a1 1 0 01-1 1H4a1 1 0 01-1-1V3a1 1 0 011-1z'))
t('dog-ear fold path', /IconDownloadReport[\s\S]{0,600}M9 2v4h4/.test(iconsSrc))
t('centered download arrow shaft', /IconDownloadReport[\s\S]{0,600}M8 7v4\.25/.test(iconsSrc))
t('arrow head chevron', /IconDownloadReport[\s\S]{0,600}M6\.1 9\.6L8 11\.5l1\.9-1\.9/.test(iconsSrc))
t('family stroke weight 1.25', /IconDownloadReport[\s\S]{0,600}strokeWidth="1\.25"/.test(iconsSrc))
t('generic IconDownload untouched (still exported)', iconsSrc.includes('export function IconDownload({ size = 16'))

// ── 2. fileExportClient — pure report builders ───────────────────────────
console.log('── 2. fileExportClient report builders ──')
const fx = await import('../lib/fileExportClient.js')
const { buildReportFilename, exportReportAsMarkdown, exportReportAsText, exportReportAsHTML } = fx

t('buildReportFilename is exported fn', typeof buildReportFilename === 'function')
t('filename: slug + date + ext', /^kivora-my-report-\d{4}-\d{2}-\d{2}\.md$/.test(buildReportFilename('My Report!', 'md')))
t('filename: spaces → dashes, lowercase', buildReportFilename('Hello World Test', 'pdf').startsWith('kivora-hello-world-test-'))
t('filename: strips special chars', !/[^a-z0-9.-]/.test(buildReportFilename('A@B#C$D', 'txt').replace(/^kivora-|-\d{4}-\d{2}-\d{2}\..+$/g, '')))
t('filename: truncates to 48 chars', (() => {
  const f = buildReportFilename('x'.repeat(120), 'md')
  const slug = f.replace(/^kivora-/, '').replace(/-\d{4}-\d{2}-\d{2}\.md$/, '')
  return slug.length <= 48
})())
t('filename: empty title → kivora-report-*', /^kivora-report-\d{4}-\d{2}-\d{2}\.html$/.test(buildReportFilename('', 'html')))

const SOURCES = [
  { url: 'https://pubmed.ncbi.nlm.nih.gov/123/', title: 'A Study <on> Things' },
  { url: 'https://example.com/src2', title: 'Second Source' },
]

// ── Markdown builder ──
const mdBlob = exportReportAsMarkdown({ title: 'T1', subtitle: 'Sub', body: 'Body **text** here [1].', sources: SOURCES })
t('md: is a Blob', mdBlob instanceof Blob)
t('md: mime text/markdown', mdBlob.type.includes('text/markdown'))
const mdText = await mdBlob.text()
t('md: h1 title', mdText.includes('# T1'))
t('md: blockquote subtitle', mdText.includes('> Sub'))
t('md: body verbatim', mdText.includes('Body **text** here [1].'))
t('md: references numbered w/ links', mdText.includes('1. [A Study <on> Things](https://pubmed.ncbi.nlm.nih.gov/123/)'))
t('md: Kivora brand footer', mdText.includes('Generated by Kivora'))
t('md: no sources → no References block', !(await exportReportAsMarkdown({ title: 'T', body: 'x' }).text()).includes('## References'))

// ── Text builder ──
const txtBlob = exportReportAsText({ title: 'T2', subtitle: 'ReelPen', body: '## Head\n- bullet **bold** `code`\n> quote', sources: SOURCES })
t('txt: is a Blob', txtBlob instanceof Blob)
t('txt: mime text/plain', txtBlob.type.includes('text/plain'))
const txtText = await txtBlob.text()
t('txt: strips header hashes', txtText.includes('Head') && !txtText.includes('## Head'))
t('txt: bullet → •', txtText.includes('• bullet bold code'))
t('txt: strips ** markers', !txtText.includes('**bold**'))
t('txt: strips backticks', !txtText.includes('`code`'))
t('txt: references with urls', txtText.includes('1. A Study <on> Things — https://pubmed.ncbi.nlm.nih.gov/123/'))

// ── HTML builder ──
const htmlBlob = exportReportAsHTML({ title: 'T3', subtitle: 'Sub', meta: 'Deep Research · 2 sources', body: '# H\n\nPara with [1] cite and [9] out-of-range.\n\n- item [2]\n\n> quote\n\n---\n\n<script>alert(1)</script>', sources: SOURCES })
t('html: is a Blob', htmlBlob instanceof Blob)
t('html: mime text/html', htmlBlob.type.includes('text/html'))
const htmlText = await htmlBlob.text()
t('html: escapes raw script tag', !htmlText.includes('<script>alert(1)') && htmlText.includes('&lt;script&gt;'))
t('html: [1] → cite link to source url', htmlText.includes('<a class="cite" href="https://pubmed.ncbi.nlm.nih.gov/123/"'))
t('html: out-of-range [9] stays literal', htmlText.includes('[9]'))
t('html: [2] → second source link', htmlText.includes('href="https://example.com/src2"'))
t('html: title escaped in <title>', htmlText.includes('<title>T3</title>'))
t('html: h1 → h2 level', htmlText.includes('<h2>H</h2>'))
t('html: bullet wrapped in list item', htmlText.includes('<li>'))
t('html: blockquote rendered', htmlText.includes('<blockquote>'))
t('html: hr rendered', htmlText.includes('<hr>'))
t('html: references section with links', htmlText.includes('References') && htmlText.includes('rel="noopener noreferrer"'))
t('html: escapes source title angle brackets', htmlText.includes('A Study &lt;on&gt; Things'))
t('html: no sources → no refs div', !(await exportReportAsHTML({ title: 'x', body: 'y' }).text()).includes('class="refs"'))
t('html: meta row carries subtitle + exported date', htmlText.includes('Deep Research · 2 sources') && htmlText.includes('Exported '))

// ── 3. fileExportHeavy ───────────────────────────────────────────────────
console.log('── 3. fileExportHeavy report exporters ──')
const heavy = await import('../lib/fileExportHeavy.js')
t('exportReportAsPDF exported', typeof heavy.exportReportAsPDF === 'function')
t('exportReportAsDOCX exported', typeof heavy.exportReportAsDOCX === 'function')
const heavySrc = read('../lib/fileExportHeavy.js')
t('PDF renders markdown headers', /exportReportAsPDF[\s\S]{0,4000}#{1,4}/.test(heavySrc))
t('PDF carries references block', /exportReportAsPDF[\s\S]{0,6000}References/.test(heavySrc))
t('PDF paginates with footer', /exportReportAsPDF[\s\S]{0,9000}Generated by Kivora/.test(heavySrc))
t('DOCX uses docx Packer', /exportReportAsDOCX[\s\S]{0,9000}Packer\.toBlob/.test(heavySrc))
t('heavy deps stay dynamic (no top-level jspdf/docx import)', !/^import .*['"]jspdf['"]|^import .*['"]docx['"]/m.test(heavySrc))

// ── 4. ExportMenu component ──────────────────────────────────────────────
console.log('── 4. ExportMenu component ──')
const menuSrc = read('../components/ExportMenu.jsx')
t("uses 'use client'", menuSrc.includes("'use client'"))
t('imports IconDownloadReport', menuSrc.includes('IconDownloadReport'))
t('renders badge chips for all formats', ['MD', 'PDF', 'DOCX', 'HTML', 'TXT', 'CSV'].every(b => menuSrc.includes(`${b}:`)))
t('click-outside closes (mousedown listener)', menuSrc.includes("document.addEventListener('mousedown'"))
t('Escape closes', menuSrc.includes("e.key === 'Escape'"))
t('cleans up listeners on unmount', menuSrc.includes('removeEventListener'))
t('busy state blocks re-entry', /busy[^}]{0,40}setBusyId/.test(menuSrc) && menuSrc.includes('if (busy) return'))
t('failure flash (errorText state)', menuSrc.includes('setFailed(true)'))
t('a11y: aria-haspopup + aria-expanded', menuSrc.includes('aria-haspopup') && menuSrc.includes('aria-expanded'))
t('null when no formats', menuSrc.includes('formats.length === 0') && menuSrc.includes('return null'))
t('spinner during async export', menuSrc.includes('IconSpinner'))

// ── 5. Page wiring ───────────────────────────────────────────────────────
console.log('── 5. Page wiring ──')
const researchSrc = read('../app/research/page.jsx')
t('research: imports ExportMenu', researchSrc.includes("import ExportMenu from '@/components/ExportMenu'"))
t('research: formats = MD/PDF/DOCX/HTML', ['md', 'pdf', 'docx', 'html'].every(id => /reportExportFormats = useMemo[\s\S]{0,700}\{ id: 'md'[\s\S]{0,900}/.test(researchSrc) && researchSrc.includes(`id: '${id}'`)))
t('research: HTML handler calls exportReportAsHTML', researchSrc.includes("exportReportAsHTML(payload), buildReportFilename(title, 'html')"))
t('research: DOCX handler dynamic-imports heavy lib', researchSrc.includes("import('@/lib/fileExportHeavy')"))
t('research: gated on reportText && !isResearching', /reportText && !isResearching && \(\s*<ExportMenu/.test(researchSrc))
t('research: passes reportExportFormats', researchSrc.includes('formats={reportExportFormats}'))
t('research: payload includes sources (citations travel)', /body: reportText,\s*sources,/.test(researchSrc))

const reelpenSrc = read('../app/reelpen/ReelPenClient.jsx')
t('reelpen: imports ExportMenu', reelpenSrc.includes("import ExportMenu from '@/components/ExportMenu'"))
t('reelpen: formats = MD/TXT/PDF', reelpenSrc.includes("id: 'md'") && reelpenSrc.includes("id: 'txt'") && reelpenSrc.includes("id: 'pdf'"))
t('reelpen: gated on result && !bpm_tapper', /result && active !== 'bpm_tapper' && \(\s*<ExportMenu/.test(reelpenSrc))
t('reelpen: passes exportFormats', reelpenSrc.includes('formats={exportFormats}'))

// ── The output box fix (user-reported: small & cut short) ──
t('reelpen: panel min-h 500 base (was 300 mobile)', reelpenSrc.includes('min-h-[500px] lg:min-h-[560px]'))
t('reelpen: old responsive min-h gone (className scope)', !/<div className="[^"]*min-h-\[300px\]/.test(reelpenSrc) && !/<div className="[^"]*sm:min-h-\[500px\]/.test(reelpenSrc))
t('reelpen: padding p-6 (was p-4 sm:p-6)', !/<div className="[^"]*p-4 sm:p-6/.test(reelpenSrc))

const studySrc = read('../app/study/StudyClient.jsx')
t('study: imports ExportMenu', studySrc.includes("import ExportMenu from '@/components/ExportMenu'"))
t('study: passes studyExportFormats', studySrc.includes('formats={studyExportFormats}'))
t('study: gated off pomodoro/quiz', /active !== 'pomodoro'[^&]*&& !\(active === 'quiz'[^)]*\) && \(\s*<ExportMenu/.test(studySrc))
t('study: formats = MD/TXT/PDF', studySrc.includes("id: 'md'") && studySrc.includes("id: 'txt'") && studySrc.includes("id: 'pdf'"))

const devSrc = read('../app/devtools/DevToolsClient.jsx')
t('devtools: imports ExportMenu', devSrc.includes("import ExportMenu from '@/components/ExportMenu'"))
t('devtools: passes devExportFormats', devSrc.includes('formats={devExportFormats}'))
t('devtools: gated on result', /result && \(\s*<ExportMenu/.test(devSrc))
t('devtools: copy+export grouped (no justify-between split)', /items-center justify-between[^>]*>\s*<h2[\s\S]{0,200}<div className="flex items-center gap-3">/.test(devSrc))

// ── 6. i18n keys ─────────────────────────────────────────────────────────
console.log('── 6. i18n keys ──')
const en = JSON.parse(read('../lib/i18n/en.json'))
for (const key of ['export.report', 'export.failed', 'export.md', 'export.pdf', 'export.docx', 'export.html', 'export.txt']) {
  t(`en.json has "${key}"`, typeof en[key] === 'string' && en[key].length > 0)
}

console.log(`\n════════════════════════════════════`)
console.log(`  export suite: ${pass} pass, ${fail} fail`)
console.log(`════════════════════════════════════`)
if (fail > 0) process.exit(1)
