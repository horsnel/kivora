let failed = false
for (const lang of ['en', 'fr', 'sw', 'yo']) {
  const p = new URL(`../lib/i18n/${lang}.json`, import.meta.url)
  const j = JSON.parse(readFileSync(p, 'utf8'))
  let added = 0
  for (const [k, v] of Object.entries(keys[lang])) {
    if (!(k in j)) {
      j[k] = v
      added++
    }
  }
  writeFileSync(p, JSON.stringify(j, null, 2) + '\n')
  console.log(lang, 'added', added, 'total', Object.keys(j).length)
}
if (failed) process.exit(1)
